// Генератор пишет метод Reset() для структур с комментарием // generate:reset в файл reset.gen.go их пакета.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"go/types"
	"io"
	"io/fs"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"unicode"

	"golang.org/x/tools/go/packages"
)

const (
	outputName = "reset.gen.go"
	marker     = "generate:reset"
	header     = "// Code generated by cmd/reset. DO NOT EDIT."
)

func main() {
	flag.Usage = func() {
		fmt.Fprintln(flag.CommandLine.Output(), "использование: reset [каталог], по умолчанию текущий каталог и все вложенные пакеты")
	}
	flag.Parse()

	root := "."
	if flag.NArg() > 0 {
		root = flag.Arg(0)
	}

	if err := run(root); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(root string) error {
	pkgs, err := load(root)
	if err != nil {
		return err
	}

	scanned := make(map[string]bool)
	marked := make(map[string]bool)
	specs := make(map[*packages.Package][]*ast.TypeSpec)
	for _, pkg := range pkgs {
		scanned[pkg.PkgPath] = true
		for _, spec := range markedSpecs(pkg) {
			specs[pkg] = append(specs[pkg], spec)
			marked[pkg.PkgPath+"."+spec.Name.Name] = true
		}
	}

	for _, pkg := range pkgs {
		if len(pkg.GoFiles) == 0 {
			continue
		}
		path := filepath.Join(filepath.Dir(pkg.GoFiles[0]), outputName)

		exists, ours, err := inspectOutput(path)
		if err != nil {
			return err
		}

		if len(specs[pkg]) == 0 {
			if exists && ours {
				if err := os.Remove(path); err != nil {
					return err
				}
			}
			continue
		}

		if exists && !ours {
			return fmt.Errorf("%s создан не генератором, перезаписывать не буду", path)
		}

		g := &generator{
			pkg:     pkg.Types,
			info:    pkg.TypesInfo,
			fset:    pkg.Fset,
			scanned: scanned,
			marked:  marked,
			imports: make(map[string]bool),
		}
		src, err := g.file(pkg.Name, specs[pkg])
		if err != nil {
			for _, e := range pkg.Errors {
				err = errors.Join(err, e)
			}
			return err
		}
		if err := os.WriteFile(path, src, 0o644); err != nil {
			return err
		}
	}

	return nil
}

func load(root string) ([]*packages.Package, error) {
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedImports | packages.NeedDeps |
			packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo,
		Dir: root,
	}

	pkgs, err := packages.Load(cfg, "./...")
	if err != nil {
		return nil, err
	}

	var errs []error
	for _, pkg := range pkgs {
		for _, e := range pkg.Errors {
			if e.Kind == packages.ParseError {
				errs = append(errs, e)
			}
		}
	}
	if len(errs) > 0 {
		return nil, errors.Join(errs...)
	}

	if !slices.ContainsFunc(pkgs, func(p *packages.Package) bool { return len(p.GoFiles) > 0 }) {
		return nil, fmt.Errorf("в %s не найдено пакетов Go", root)
	}

	return pkgs, nil
}

func markedSpecs(pkg *packages.Package) []*ast.TypeSpec {
	var specs []*ast.TypeSpec

	for _, file := range pkg.Syntax {
		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				doc := ts.Doc
				if !gd.Lparen.IsValid() {
					doc = gd.Doc
				}
				if hasMarker(doc) {
					specs = append(specs, ts)
				}
			}
		}
	}

	return specs
}

func hasMarker(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}
	for _, c := range doc.List {
		if strings.TrimSpace(strings.TrimPrefix(c.Text, "//")) == marker {
			return true
		}
	}
	return false
}

func inspectOutput(path string) (exists, ours bool, err error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return false, false, nil
	}
	if err != nil {
		return false, false, err
	}
	return true, bytes.HasPrefix(data, []byte(header)), nil
}

type generator struct {
	pkg     *types.Package
	info    *types.Info
	fset    *token.FileSet
	scanned map[string]bool
	marked  map[string]bool
	imports map[string]bool
}

func (g *generator) file(name string, specs []*ast.TypeSpec) ([]byte, error) {
	var methods bytes.Buffer
	for _, spec := range specs {
		if err := g.method(&methods, spec); err != nil {
			return nil, err
		}
	}

	var src bytes.Buffer
	fmt.Fprintf(&src, "%s\n\npackage %s\n\n", header, name)
	if len(g.imports) > 0 {
		src.WriteString("import (\n")
		for _, path := range slices.Sorted(maps.Keys(g.imports)) {
			fmt.Fprintf(&src, "%q\n", path)
		}
		src.WriteString(")\n\n")
	}
	src.Write(methods.Bytes())

	return format.Source(src.Bytes())
}

func (g *generator) method(w io.Writer, spec *ast.TypeSpec) error {
	name := spec.Name.Name
	pos := g.fset.Position(spec.Pos())

	if spec.TypeParams != nil {
		return fmt.Errorf("%s: %s: обобщённые типы не поддерживаются", pos, name)
	}

	obj, ok := g.info.Defs[spec.Name].(*types.TypeName)
	if !ok || obj.IsAlias() {
		return fmt.Errorf("%s: %s: пометку %s ставят только на объявление структуры", pos, name, marker)
	}
	named := obj.Type().(*types.Named)
	st, ok := named.Underlying().(*types.Struct)
	if !ok {
		return fmt.Errorf("%s: %s не структура", pos, name)
	}

	for m := range named.Methods() {
		if m.Name() == "Reset" && !g.generated(m) {
			return fmt.Errorf("%s: у %s уже есть свой метод Reset", g.fset.Position(m.Pos()), name)
		}
	}

	recv := g.receiver(named)

	fmt.Fprintf(w, "// Reset сбрасывает %s к начальному состоянию.\n", name)
	fmt.Fprintf(w, "func (%s *%s) Reset() {\n", recv, name)
	fmt.Fprintf(w, "if %s == nil {\nreturn\n}\n\n", recv)

	for field := range st.Fields() {
		if field.Name() == "_" {
			continue
		}
		if err := g.reset(w, recv+"."+field.Name(), field.Type()); err != nil {
			return fmt.Errorf("%s: поле %s: %w", g.fset.Position(field.Pos()), field.Name(), err)
		}
	}

	fmt.Fprint(w, "}\n\n")
	return nil
}

func (g *generator) reset(w io.Writer, expr string, typ types.Type) error {
	t := types.Unalias(typ)

	if g.hasReset(t) {
		fmt.Fprintf(w, "%s.Reset()\n", paren(expr))
		return nil
	}

	switch u := t.Underlying().(type) {
	case *types.Basic:
		zero, err := basicZero(u)
		if err != nil {
			return err
		}
		fmt.Fprintf(w, "%s = %s\n", expr, zero)
	case *types.Slice:
		fmt.Fprintf(w, "%s = %s[:0]\n", expr, paren(expr))
	case *types.Map:
		fmt.Fprintf(w, "clear(%s)\n", expr)
	case *types.Pointer:
		elem := types.Unalias(u.Elem())
		switch {
		case g.hasReset(elem):
			fmt.Fprintf(w, "if %s != nil {\n%s.Reset()\n}\n", expr, paren(expr))
		case resetInPlace(elem):
			fmt.Fprintf(w, "if %s != nil {\n", expr)
			if err := g.reset(w, "*"+expr, elem); err != nil {
				return err
			}
			fmt.Fprint(w, "}\n")
		default:
			fmt.Fprintf(w, "%s = nil\n", expr)
		}
	case *types.Struct, *types.Array:
		fmt.Fprintf(w, "%s = %s{}\n", expr, types.TypeString(typ, g.qualify))
	default:
		fmt.Fprintf(w, "%s = nil\n", expr)
	}

	return nil
}

func (g *generator) hasReset(t types.Type) bool {
	if n, ok := t.(*types.Named); ok && n.Obj().Pkg() != nil && g.marked[n.Obj().Pkg().Path()+"."+n.Obj().Name()] {
		return true
	}

	switch t.Underlying().(type) {
	case *types.Interface, *types.Pointer:
		return false
	}

	obj, index, _ := types.LookupFieldOrMethod(t, true, g.pkg, "Reset")
	fn, ok := obj.(*types.Func)
	if !ok || len(index) > 1 || g.generated(fn) {
		return false
	}
	sig := fn.Signature()
	return sig.Params().Len() == 0 && sig.Results().Len() == 0
}

func (g *generator) generated(fn *types.Func) bool {
	return fn.Pkg() != nil && g.scanned[fn.Pkg().Path()] &&
		filepath.Base(g.fset.Position(fn.Pos()).Filename) == outputName
}

func (g *generator) receiver(named *types.Named) string {
	for m := range named.Methods() {
		if g.generated(m) {
			continue
		}
		if recv := m.Signature().Recv(); recv != nil && recv.Name() != "" && recv.Name() != "_" {
			return recv.Name()
		}
	}

	first := []rune(named.Obj().Name())[0]
	return string(unicode.ToLower(first))
}

func (g *generator) qualify(p *types.Package) string {
	if p == g.pkg {
		return ""
	}
	g.imports[p.Path()] = true
	return p.Name()
}

func resetInPlace(t types.Type) bool {
	switch t.Underlying().(type) {
	case *types.Basic, *types.Slice, *types.Map, *types.Pointer:
		return true
	}
	return false
}

func basicZero(b *types.Basic) (string, error) {
	switch {
	case b.Info()&types.IsBoolean != 0:
		return "false", nil
	case b.Info()&types.IsString != 0:
		return `""`, nil
	case b.Info()&types.IsNumeric != 0:
		return "0", nil
	}
	return "", fmt.Errorf("не удалось определить тип %s", b)
}

func paren(expr string) string {
	if strings.HasPrefix(expr, "*") {
		return "(" + expr + ")"
	}
	return expr
}
